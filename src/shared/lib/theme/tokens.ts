export const THEME_PRESETS: Record<ThemePreset, ThemePresetDefinition> = {
  "warm-tactile": warmTactilePreset,
  "editorial-slate": editorialSlatePreset,
  "neo-brutalist": neoBrutalistPreset,
};

export function isThemePreset(value: unknown): value is ThemePreset {
  return value === "warm-tactile" || value === "editorial-slate" || value === "neo-brutalist";
}

export function isThemeMode(value: unknown): value is ThemeMode {
  return value === "system" || value === "light" || value === "dark";
}

export function getThemeTokenMap(preset: ThemePreset, scheme: ResolvedColorScheme): ThemeTokenMap {
  return THEME_PRESETS[preset][scheme];
}

export function resolveThemeColor(
  preset: ThemePreset,
  scheme: ResolvedColorScheme,
  token: ThemeColorToken,
): string {
  const channels = THEME_PRESETS[preset][scheme][`--${token}`];
  return `hsl(${channels})`;
}

export function getThemeElevation(
  preset: ThemePreset,
  scheme: ResolvedColorScheme,
): ThemePresetElevation {
  return THEME_PRESETS[preset].elevation[scheme];
}
